def _generator_options(seed=0, max_cells=0, raster_rule=None):
    """Build call-scoped checked-generator options without callback retention."""
    options = ffi.new("obstacle_generate_options_t*")
    raise_for_status(
        C.obstacle_generate_options_init(options),
        "obstacle_generate_options_init",
    )
    options.seed = seed
    options.max_cells = max_cells
    if raster_rule is not None:
        options.raster_rule = raster_rule
    return options


def _coord_argument(value, argument):
    if isinstance(value, c_coord):
        return value._require_open()
    try:
        x, y = value
    except (TypeError, ValueError):
        raise TypeError(f"{argument} must be c_coord or an (x, y) pair") from None
    return ffi.new("coord_t*", {"x": x, "y": y})


def _coord_buffer(vertices):
    values = [(value.x, value.y) if isinstance(value, c_coord) else tuple(value)
              for value in vertices]
    if any(len(value) != 2 for value in values):
        raise TypeError("each vertex must be c_coord or an (x, y) pair")
    return ffi.new("coord_t[]", [dict(x=x, y=y) for x, y in values])


class c_obstacle:
    def __init__(self, x0=0, y0=0, width=0, height=0, raw_ptr=None, own=True):
        _check_obstacle_abi()
        self._own = own
        self._c = raw_ptr if raw_ptr is not None else ffi.NULL
        self._finalizer = None
        if self._c == ffi.NULL:
            output = ffi.new("obstacle_t**")
            raise_for_status(
                C.obstacle_create_checked(x0, y0, width, height, output),
                "obstacle_create_checked",
            )
            self._c = output[0]
        if own:
            self._finalizer = weakref.finalize(self, C.obstacle_destroy, self._c)

    @classmethod
    def _from_generator(cls, operation, invoke):
        output = ffi.new("obstacle_t**")
        raise_for_status(invoke(output), operation)
        if output[0] == ffi.NULL:
            raise RuntimeError(f"{operation} returned OK with a NULL obstacle")
        return cls(raw_ptr=output[0], own=True)

    @classmethod
    def generate_filled_rect(cls, x0, y0, width, height, *, max_cells=0):
        options = _generator_options(max_cells=max_cells)
        return cls._from_generator(
            "obstacle_generate_filled_rect",
            lambda output: C.obstacle_generate_filled_rect(
                x0, y0, width, height, options, output),
        )

