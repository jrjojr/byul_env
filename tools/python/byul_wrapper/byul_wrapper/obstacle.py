OBSTACLE_ABI_VERSION = 2
OBSTACLE_ABI_FINGERPRINT = 0x4F42535402000000


def _check_obstacle_abi():
    mismatch = ffi.new("obstacle_abi_mismatch_t*")
    try:
        status = NavsysStatus(
            C.obstacle_check_abi(
                OBSTACLE_ABI_VERSION,
                OBSTACLE_ABI_FINGERPRINT,
                mismatch,
            )
        )
    except AttributeError as error:
        raise RuntimeError(
            "Obstacle ABI mismatch: runtime does not export obstacle_check_abi"
        ) from error
    if status is NavsysStatus.OK:
        return
    reason = {1: "version", 2: "fingerprint"}.get(
        int(mismatch[0]), "unknown"
    )
    raise RuntimeError(
        f"Obstacle ABI mismatch: {reason}; "
        f"expected version={OBSTACLE_ABI_VERSION} "
        f"fingerprint=0x{OBSTACLE_ABI_FINGERPRINT:016x}"
    )


